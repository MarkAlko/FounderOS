export function matchPageHelp(pathname: string): PageHelp | undefined {
  const path = pathname.split('?')[0] || '/';
  if (PAGE_HELP[path]) return PAGE_HELP[path];
  const parts = path.split('/').filter(Boolean);
  for (const key of Object.keys(PAGE_HELP)) {
    const keys = key.split('/').filter(Boolean);
    if (keys.length !== parts.length) continue;
    const ok = keys.every((segment, i) => (segment.startsWith('[') && segment.endsWith(']')) || segment === parts[i]);
    if (ok) return PAGE_HELP[key];
  }
  return undefined;
}
